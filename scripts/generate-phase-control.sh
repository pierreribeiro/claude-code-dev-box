#!/bin/bash
# Generate Phase Control and Context Migration Artifacts
# Author: Pierre Ribeiro
# Version: 1.0.0

set -e
set -u

# Colors
BLUE='\033[0;34m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

PHASE=$1
if [ -z "$PHASE" ]; then
    echo -e "${YELLOW}Usage:${NC} $0 <phase_number>"
    echo "Example: $0 0"
    exit 1
fi

DATE=$(date +%Y-%m-%d)
TIME=$(date +%H:%M:%S)
GIT_COMMIT=$(git rev-parse --short HEAD 2>/dev/null || echo "N/A")
GIT_BRANCH=$(git branch --show-current 2>/dev/null || echo "N/A")

echo -e "${BLUE}Generating artifacts for Phase ${PHASE}...${NC}"

# Ensure directories exist
mkdir -p docs/control docs/migration

# Generate Control Artifact
cat > docs/control/phase-${PHASE}-control.md << EOF
# Phase ${PHASE} Control Document

**Phase**: ${PHASE}  
**Date**: ${DATE}  
**Session Start**: ${TIME}  
**Session Duration**: [TO BE FILLED]  
**Status**: Complete

---

## Completed Tasks

EOF

if [ "$PHASE" -eq 0 ]; then
    cat >> docs/control/phase-${PHASE}-control.md << 'EOF'
- [x] Bootstrap script created (scripts/phase-0-bootstrap.sh)
- [x] Git repository initialized
- [x] Ansible installed via apt
- [x] pipx installed for future tools
- [x] Directory structure created
- [x] .gitignore configured
- [x] README.md created
- [x] Control artifact generation script created

EOF
else
    cat >> docs/control/phase-${PHASE}-control.md << EOF
- [x] Phase ${PHASE} tasks completed
- [ ] (Add specific tasks as needed)

EOF
fi

cat >> docs/control/phase-${PHASE}-control.md << EOF
## Pending Tasks

EOF

if [ "$PHASE" -eq 0 ]; then
    cat >> docs/control/phase-${PHASE}-control.md << 'EOF'
- [ ] Phase 1: System Preparation (apt packages)
- [ ] Phase 2: Homebrew Installation

EOF
else
    NEXT_PHASE=$((PHASE + 1))
    cat >> docs/control/phase-${PHASE}-control.md << EOF
- [ ] Phase ${NEXT_PHASE}: (To be defined)

EOF
fi

cat >> docs/control/phase-${PHASE}-control.md << EOF
## Issues Encountered

None

## Configuration Changes

EOF

if [ "$PHASE" -eq 0 ]; then
    cat >> docs/control/phase-${PHASE}-control.md << 'EOF'
- Created: Project root structure
- Installed: Ansible $(ansible --version | head -1 2>/dev/null || echo "(version check failed)")
- Installed: pipx
- Configured: Git user and email

EOF
else
    cat >> docs/control/phase-${PHASE}-control.md << EOF
- (Add configuration changes as needed)

EOF
fi

cat >> docs/control/phase-${PHASE}-control.md << EOF
## Validation Results

\`\`\`bash
# Validation commands here
EOF

if [ "$PHASE" -eq 0 ]; then
    cat >> docs/control/phase-${PHASE}-control.md << 'EOF'
$ ansible --version
ansible [core 2.15.x]

$ git status
On branch develop
nothing to commit, working tree clean

$ ls -la
total XYZ
drwxr-xr-x ... playbooks/
drwxr-xr-x ... roles/
drwxr-xr-x ... scripts/
...
EOF
fi

cat >> docs/control/phase-${PHASE}-control.md << EOF
\`\`\`

## Next Session Instructions

EOF

if [ "$PHASE" -eq 0 ]; then
    cat >> docs/control/phase-${PHASE}-control.md << 'EOF'
1. Load Main PRD: Phase 1 section
2. Review this control document
3. Run: ansible-playbook playbooks/main.yml --tags phase1
4. Generate Phase 1 control artifact after completion

EOF
else
    NEXT_PHASE=$((PHASE + 1))
    cat >> docs/control/phase-${PHASE}-control.md << EOF
1. Load Main PRD: Phase ${NEXT_PHASE} section
2. Review this control document  
3. Run: ansible-playbook playbooks/main.yml --tags phase${NEXT_PHASE}
4. Generate Phase ${NEXT_PHASE} control artifact

EOF
fi

cat >> docs/control/phase-${PHASE}-control.md << EOF
---

*Generated by: scripts/generate-phase-control.sh*  
*Git Commit: ${GIT_COMMIT}*  
*Git Branch: ${GIT_BRANCH}*
EOF

echo -e "${GREEN}✓${NC} Control artifact: docs/control/phase-${PHASE}-control.md"

# Generate Context Migration Artifact
cat > docs/migration/phase-${PHASE}-migration.md << EOF
# Context Migration - Phase ${PHASE} → Phase $((PHASE+1))

**From Phase**: ${PHASE}  
**To Phase**: $((PHASE+1))  
**Date**: ${DATE}  
**Time**: ${TIME}

---

## Session Summary

- **Duration**: [TO BE FILLED]
- **Phase Completed**: Phase ${PHASE}
- **Git Commit**: ${GIT_COMMIT}
- **Git Branch**: ${GIT_BRANCH}
- **Git Tag**: phase-${PHASE}-complete

## Technical State

### Installed Tools

EOF

if [ "$PHASE" -eq 0 ]; then
    cat >> docs/migration/phase-${PHASE}-migration.md << 'EOF'
- Git: $(git --version 2>/dev/null || echo "Not installed")
- Ansible: $(ansible --version 2>/dev/null | head -1 || echo "Not installed")
- Python: $(python3 --version 2>/dev/null || echo "Not installed")
- pipx: $(pipx --version 2>/dev/null || echo "Not installed")

EOF
fi

cat >> docs/migration/phase-${PHASE}-migration.md << EOF
### Repository State

\`\`\`bash
Repository: $(pwd)
Branch: ${GIT_BRANCH}
Last Commit: $(git log -1 --oneline 2>/dev/null || echo "N/A")
\`\`\`

### File Structure

\`\`\`
EOF

tree -L 2 -I '__pycache__|*.pyc|.git' >> docs/migration/phase-${PHASE}-migration.md 2>/dev/null || echo "(tree command not available)" >> docs/migration/phase-${PHASE}-migration.md

cat >> docs/migration/phase-${PHASE}-migration.md << EOF
\`\`\`

## Environment Variables

\`\`\`bash
# None set yet (base system)
\`\`\`

## Carry Forward to Phase $((PHASE+1))

### Actions Required

EOF

if [ "$PHASE" -eq 0 ]; then
    cat >> docs/migration/phase-${PHASE}-migration.md << 'EOF'
1. Create system_preparation role
2. Define apt packages in variables
3. Implement idempotent installation tasks
4. Create ansible.cfg
5. Create inventory/hosts.yml

EOF
else
    cat >> docs/migration/phase-${PHASE}-migration.md << EOF
1. (Define actions for Phase $((PHASE+1)))

EOF
fi

cat >> docs/migration/phase-${PHASE}-migration.md << EOF
### Reference Files

- Main PRD: docs/PRD_WSL2_ClaudeCode_DevBox_Unified_v1.0.0.md
- This Control: docs/control/phase-${PHASE}-control.md

### Context Summary

EOF

if [ "$PHASE" -eq 0 ]; then
    cat >> docs/migration/phase-${PHASE}-migration.md << 'EOF'
Phase 0 established the foundation:
- Git repository with proper structure
- Ansible installed and ready
- Bootstrap process documented and repeatable
- Control artifact generation automated

Next phase will focus on system package installation using Ansible roles.

EOF
fi

cat >> docs/migration/phase-${PHASE}-migration.md << EOF
---

*Generated by: scripts/generate-phase-control.sh*  
*Git Commit: ${GIT_COMMIT}*  
*Git Branch: ${GIT_BRANCH}*
EOF

echo -e "${GREEN}✓${NC} Migration artifact: docs/migration/phase-${PHASE}-migration.md"
echo ""
echo -e "${BLUE}Artifacts generated successfully!${NC}"
echo ""
